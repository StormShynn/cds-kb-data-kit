#!/usr/bin/env node
// scripts/refresh-vsp-cookie.mjs
// Semi-automated replacement for "F12 → copy cookies → paste into
// tools/vsp/cookies.txt by hand" — the tenant's SAML SSO login has MFA, so a
// fully unattended login (storing a username/password somewhere to replay
// the SAML POST automatically) isn't something this script attempts: MFA
// can't be scripted safely, and stashing a password to get past the first
// factor wouldn't actually remove the need for a human at the second factor
// anyway. Instead this opens a REAL, visible browser window, lets you log
// in exactly as you would normally (MFA included), and once you confirm
// you're in, reads that browser's own cookies and writes them straight to
// cookies.txt in the Netscape format vsp.exe expects — no credentials ever
// touch this script or get stored anywhere.
//
// Requires the "playwright" devDependency and its Chromium browser binary:
//   npm install
//   npx playwright install chromium
//
// Usage:
//   node scripts/refresh-vsp-cookie.mjs [--system sap_cloud_dev]

import fs from 'node:fs/promises';
import path from 'node:path';
import readline from 'node:readline';

const DATA_DIR = '.';
const VSP_CONFIG = path.join(DATA_DIR, '.vsp.json');

function parseArgs() {
  const args = process.argv.slice(2);
  const opts = {};
  const i = args.indexOf('--system');
  if (i !== -1) opts.system = args[i + 1];
  return opts;
}

async function waitForEnter(promptText) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  await new Promise((resolve) => rl.question(promptText, resolve));
  rl.close();
}

// Netscape/Mozilla cookie file format — the same one curl and vsp.exe read:
// domain \t includeSubdomains \t path \t secure \t expiry(unix, 0=session) \t name \t value
function toNetscapeCookieFile(cookies) {
  const lines = [
    '# Netscape HTTP Cookie File',
    '# https://curl.haxx.se/rfc/cookie_spec.html',
    '# Generated by scripts/refresh-vsp-cookie.mjs — do not edit by hand.',
    '',
  ];
  for (const c of cookies) {
    const includeSubdomains = c.domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expiry = c.expires && c.expires > 0 ? Math.floor(c.expires) : 0;
    lines.push([c.domain, includeSubdomains, c.path || '/', c.secure ? 'TRUE' : 'FALSE', expiry, c.name, c.value].join('\t'));
  }
  return lines.join('\n') + '\n';
}

async function main() {
  const opts = parseArgs();

  let playwright;
  try {
    playwright = await import('playwright');
  } catch {
    console.error('Thiếu "playwright". Chạy: npm install && npx playwright install chromium');
    process.exit(1);
  }

  let vspConfig;
  try {
    vspConfig = JSON.parse(await fs.readFile(VSP_CONFIG, 'utf-8'));
  } catch {
    console.error(`Không tìm thấy hoặc không đọc được ${VSP_CONFIG}.`);
    process.exit(1);
  }
  const systemName = opts.system || vspConfig.default || Object.keys(vspConfig.systems || {})[0];
  const system = vspConfig.systems?.[systemName];
  if (!system) {
    console.error(`Không tìm thấy system "${systemName}" trong ${VSP_CONFIG}.`);
    process.exit(1);
  }
  if (!system.cookie_file) {
    console.error(`System "${systemName}" thiếu "cookie_file" trong ${VSP_CONFIG}.`);
    process.exit(1);
  }

  console.log(`Mở trình duyệt tới ${system.url} (system: ${systemName})...`);
  const browser = await playwright.chromium.launch({ headless: false });
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto(system.url);

  console.log('\nĐăng nhập bình thường trong cửa sổ trình duyệt vừa mở (kể cả MFA/OTP).');
  console.log('Sau khi đã vào được trang chính (Fiori Launchpad), quay lại đây và nhấn Enter.');
  await waitForEnter('Nhấn Enter khi đã đăng nhập xong... ');

  const cookies = await context.cookies();
  const tenantHost = new URL(system.url).hostname;
  const hasTenantCookie = cookies.some((c) => c.domain.replace(/^\./, '') === tenantHost || tenantHost.endsWith(c.domain.replace(/^\./, '')));
  if (cookies.length === 0 || !hasTenantCookie) {
    console.error(`Không thấy cookie nào của chính "${tenantHost}" (chỉ có cookie theo dõi chung nếu có) — có vẻ chưa đăng nhập xong. Không ghi đè ${system.cookie_file}.`);
    await browser.close();
    process.exit(1);
  }

  // Keep the previous cookie file around in case the new one turns out to
  // be worse somehow — cheap insurance against overwriting a working
  // session with a broken capture.
  try {
    await fs.copyFile(system.cookie_file, system.cookie_file + '.bak');
  } catch {}

  const cookieFileContent = toNetscapeCookieFile(cookies);
  await fs.mkdir(path.dirname(system.cookie_file), { recursive: true });
  await fs.writeFile(system.cookie_file, cookieFileContent, 'utf-8');
  console.log(`\n✅ Đã ghi ${cookies.length} cookie vào ${system.cookie_file} (bản cũ lưu ở ${system.cookie_file}.bak)`);

  await browser.close();
}

main().catch((err) => {
  console.error(`Lỗi: ${err.message}`);
  process.exit(1);
});
